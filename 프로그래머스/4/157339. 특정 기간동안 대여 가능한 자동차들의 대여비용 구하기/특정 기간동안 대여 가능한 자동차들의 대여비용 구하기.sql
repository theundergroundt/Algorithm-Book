SELECT C.CAR_ID, C.CAR_TYPE, C.DAILY_FEE*30*(1-P.DISCOUNT_RATE/100) as FEE
from CAR_RENTAL_COMPANY_CAR C join CAR_RENTAL_COMPANY_DISCOUNT_PLAN P on C.CAR_TYPE = P.CAR_TYPE and P.DURATION_TYPE = '30일 이상'
where C.CAR_TYPE in ('세단', 'SUV') 
and C.CAR_ID not in (select CAR_ID from CAR_RENTAL_COMPANY_RENTAL_HISTORY
                where END_DATE >= '2022-11-01' and START_DATE <= '2022-11-30'
          )
          and C.DAILY_FEE*30*(1-P.DISCOUNT_RATE/100) >=500000
          and C.DAILY_FEE*30*(1-P.DISCOUNT_RATE/100) <2000000
order by FEE desc, C.CAR_TYPE asc, C.CAR_ID desc;