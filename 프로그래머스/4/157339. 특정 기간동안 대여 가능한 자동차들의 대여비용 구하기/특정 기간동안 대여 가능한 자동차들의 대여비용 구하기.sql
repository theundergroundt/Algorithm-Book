SELECT C.CAR_ID, C.CAR_TYPE, 30*C.DAILY_FEE*(1-P.DISCOUNT_RATE/100) AS FEE
FROM CAR_RENTAL_COMPANY_CAR C join CAR_RENTAL_COMPANY_DISCOUNT_PLAN P on C.CAR_TYPE = P.CAR_TYPE AND DURATION_TYPE = '30일 이상'
where C.CAR_TYPE in ('세단', 'SUV') and C.CAR_ID NOT IN (
    select CAR_ID 
    from CAR_RENTAL_COMPANY_RENTAL_HISTORY
    where END_DATE >= '2022-11-01' and START_DATE <= '2022-11-30')
    and 30*C.DAILY_FEE*(1-P.DISCOUNT_RATE/100) >= 500000 
    AND 30*C.DAILY_FEE*(1-P.DISCOUNT_RATE/100) <2000000
ORDER BY FEE DESC, C.CAR_TYPE ASC, C.CAR_ID DESC;
